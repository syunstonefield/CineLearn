// 和訳 API（/api/claude の sentence・sentences・wordsense）に渡してよい「英語字幕の1文」か（2026-10-13 セキュリティ監査 H1）。
//
// 背景: 共有訳キャッシュのキー senseHash は [^a-z0-9] を全て捨ててハッシュする（引用符・空白の揺れを吸収するため）。
//   一方プロンプトには原文がそのまま入る。だから「正規例文＋日本語（や記号）だけの指示」を送ると、モデルは指示に従い、
//   その結果が**正規例文と同じキー**で translation_ctx_cache → vocab_cache.example_ja に恒久追記された（空欄のみ追記＝消えない）。
//   キーが変わらない追記は [a-z0-9] を1字も含まない文字列に限られる＝CJK・かな・キリル等で指示を書く経路。
//   ここで英語字幕に出る文字だけを許し、それ以外を含む文はプロンプトにもキャッシュにも届かせない。
//
// 許可: タブ・改行（CR/LF）／ASCII 印字可能（U+0020–007E）／Latin-1 補助（U+00A0–00FF: café・¿¡ 等）／
//       字幕で普通に出る記号 – — ‘ ’ ‚ “ ” … と ♪ ♫（歌詞行。OpenSubtitles の SRT と配信画面の行に頻出）。
//   ♪♫ は指定外の追加: 拡張の wordsense は配信画面の字幕行をそのまま送るため、歌詞行で語義が引けなくなるのを避ける。
//   記号2字では指示文を書けない＝衝突の足場にならない。
// 拒否: 上記以外すべて（CJK・ひらがな/カタカナ・キリル・その他の制御文字・絵文字…）。
//   残る衝突余地は「Latin-1 の記号/アクセント付き文字だけの追記」＝意味のある指示文を組めない。
//
// クライアント（単語帳・単語リストの一括訳）も同じ判定で事前に除外する＝1文の拒否でバッチ全体が 400 にならない。
// 依存なし（サーバ route・クライアント・node:test のどこからでも import できる）。

export const SUBTITLE_SENTENCE_MAX = 400; // 1文の上限（サーバの切り詰め 300 字の手前で、長すぎる入力そのものを弾く）

const ALLOWED_RE = /^[\t\n\r -~ -ÿ–—‘-”…♪♫]*$/;

// 文字列で、max 字以内で、許可文字だけから成るか。空文字は true（空の判定は呼び出し側の 'bad request' に任せる）。
export function isSubtitleSentence(s, max = SUBTITLE_SENTENCE_MAX) {
  return typeof s === 'string' && s.length <= max && ALLOWED_RE.test(s);
}
